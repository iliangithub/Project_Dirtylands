# ABOUTME: crontab que GUARDA de verdad lo que le instalan, en su spool.
# ABOUTME: El de la imagen se lo tragaba todo y ademas colgaba la sesion.
#
# EL DE LA IMAGEN COLGABA LA SESION. "crontab -" ---que es exactamente como se
# instala una tarea desde un guion, y de las tres formas de persistir la mas
# usada--- no encajaba en ninguna de sus ramas: caia en un "if len(self.args):
# pass" y NO LLAMABA a exit(). El atacante se quedaba sin prompt, mirando una
# sesion que parecia colgada.
#
# Y lo que no colgaba, mentia. Nada se guardaba, asi que
#
#     echo '* * * * * /tmp/x' | crontab -
#     crontab -l
#     no crontab for root
#
# se contradecia solo en dos ordenes seguidas. Ahora se escribe donde lo
# escribe cron ---/var/spool/cron/crontabs/USUARIO--- para que un "cat" de esa
# ruta y el "crontab -l" cuenten lo mismo.
#
# Todo medido contra el cron de un Debian 13, incluida la cabecera de tres
# lineas que crontab mete en el fichero y que "crontab -l" NO ensena.
from __future__ import annotations

import getopt
import time

from cowrie.commands.base import FallaAlAvisar
from cowrie.shell.command import HoneyPotCommand

commands = {}

SPOOL = "/var/spool/cron/crontabs"

USO = """usage:\tcrontab [-u user] [-n] file
\tcrontab [ -u user ] [ -i ] { -e | -l | -r }

\t-h\t(displays this help message)

\tfile\t(default operation is replace, per 1003.2)
\t-n\t(dry run: checks the syntax, then bails out)
\t-u user\t(choose the user whose crontab is touched)

\t-e\t(edit user's crontab)
\t-l\t(list user's crontab)
\t-r\t(delete user's crontab)

\t-i\t(prompt before deleting user's crontab)
"""

CABECERA = (
    "# DO NOT EDIT THIS FILE - edit the master and reinstall.\n"
    "# (%s installed on %s)\n"
    "# (Cron version -- $Id: crontab.c,v 2.13 1994/01/17 03:20:37 vixie Exp $)\n"
)


class Command_crontab(FallaAlAvisar, HoneyPotCommand):
    def ruta(self, usuario: str) -> str:
        return "%s/%s" % (SPOOL, usuario)

    def existe_usuario(self, nombre: str) -> bool:
        try:
            datos = self.fs.file_contents("/etc/passwd").decode(
                "utf-8", "replace")
        except Exception:                                      # noqa: BLE001
            return True
        return any(l.split(":")[0] == nombre for l in datos.splitlines() if l)

    def leer(self, usuario: str):
        """El crontab guardado, ya sin la cabecera, o None si no hay."""
        try:
            datos = self.fs.file_contents(self.ruta(usuario))
        except Exception:                                      # noqa: BLE001
            return None
        lineas = datos.decode("utf-8", "replace").split("\n")
        # Las tres lineas de cabecera las pone crontab y NO las ensena al
        # listar: medido. Solo se quitan si estan.
        if len(lineas) >= 3 and lineas[0].startswith("# DO NOT EDIT THIS FILE"):
            lineas = lineas[3:]
        return "\n".join(lineas)

    def guardar(self, usuario: str, cuerpo: str, origen: str) -> bool:
        from cowrie.commands.base import escribe_fichero

        # El spool puede no existir en el sistema de ficheros: se crea, que es
        # lo que hace el paquete cron al instalarse.
        for directorio in ("/var/spool/cron", SPOOL):
            if not self.fs.exists(directorio):
                try:
                    self.fs.mkdir(directorio, 0, 0, 4096, 16877)
                except Exception:                              # noqa: BLE001
                    pass
        texto = CABECERA % (
            origen, time.strftime("%a %b %e %H:%M:%S %Y")) + cuerpo
        # 0600 y root:crontab, que es como lo deja cron: medido.
        return escribe_fichero(self, self.ruta(usuario), texto.encode(),
                               modo=33152)

    def start(self) -> None:
        try:
            opts, args = getopt.getopt(self.args, "u:elrinh")
        except getopt.GetoptError as err:
            self.errorWrite("crontab: option requires an argument -- '%s'\n"
                            % err.opt)
            self.errorWrite("crontab: usage error: unrecognized option\n")
            self.errorWrite(USO)
            self.exit()
            return

        usuario = self.protocol.user.username
        accion = ""
        for o, a in opts:
            if o == "-u":
                usuario = a
            elif o == "-h":
                self.write(USO)
                self.exit()
                return
            elif o != "-i":
                accion = o

        if not self.existe_usuario(usuario):
            self.errorWrite("crontab:  user `%s' unknown\n" % usuario)
            self.exit()
            return

        if accion == "-l":
            cuerpo = self.leer(usuario)
            if cuerpo is None:
                self.errorWrite("no crontab for %s\n" % usuario)
            else:
                self.write(cuerpo)
            self.exit()
            return

        if accion == "-r":
            if self.leer(usuario) is None:
                self.errorWrite("no crontab for %s\n" % usuario)
            else:
                try:
                    self.fs.remove(self.ruta(usuario))
                except Exception:                              # noqa: BLE001
                    pass
            self.exit()
            return

        if accion == "-e":
            # Sin EDITOR, Debian va a /usr/bin/editor y las alternativas lo
            # llevan a nano, que esta instalado. Se le entrega el fichero del
            # spool: lo que el atacante escriba y guarde QUEDA instalado, que
            # es lo que pasa de verdad.
            editor = self.environ.get("EDITOR") or self.environ.get("VISUAL") \
                or "nano"
            if not self.fs.exists(self.ruta(usuario)):
                self.guardar(usuario, "", "-")
            from cowrie.commands.bashbuiltins import _relanzar

            _relanzar(self, "%s %s" % (editor, self.ruta(usuario)))
            self.exit()
            return

        if not args:
            # "crontab" a secas se queda leyendo la entrada, como el de verdad.
            if self.input_data is None:
                return
            args = ["-"]

        origen = args[0]
        if origen == "-":
            cuerpo = (self.input_data or b"").decode("utf-8", "replace")
        else:
            try:
                cuerpo = self.fs.file_contents(
                    self.fs.resolve_path(origen, self.protocol.cwd)
                ).decode("utf-8", "replace")
            except Exception:                                  # noqa: BLE001
                self.errorWrite("%s: No such file or directory\n" % origen)
                self.exit()
                return
        if "-n" not in [o for o, _a in opts]:
            self.guardar(usuario, cuerpo, origen)
        self.exit()

    def lineReceived(self, line: str) -> None:
        self.protocol.events.dispatch(
            "cowrie.command.input",
            "INPUT (%(realm)s): %(input)s",
            realm="crontab",
            input=line,
        )
        self.datos = getattr(self, "datos", "") + line + "\n"

    def eofReceived(self) -> None:
        # Lo que llego por la entrada de la terminal ---"crontab -" tecleado a
        # mano y terminado con Ctrl-D--- tambien se instala.
        cuerpo = getattr(self, "datos", "")
        if cuerpo:
            self.guardar(self.protocol.user.username, cuerpo, "-")
        self.exit()


commands["/usr/bin/crontab"] = Command_crontab
commands["crontab"] = Command_crontab
