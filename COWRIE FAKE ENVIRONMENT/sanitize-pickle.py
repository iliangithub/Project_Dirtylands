def patch_proc_del_proceso(tree):
    """Rellena /proc del proceso de la sesion y de init.

    Va DESPUES de patch_pid_del_constructor: hasta entonces el directorio se
    llama como el PID del contenedor que genero el pickle.
    """
    trabajos = [
        ("/proc/%d/status" % PID_LEYENDA,
         make_status("bash", PID_LEYENDA, PPID_LEYENDA,
                     VSZ_SESION, RSS_SESION)),
        ("/proc/%d/stat" % PID_LEYENDA,
         make_stat("bash", PID_LEYENDA, PPID_LEYENDA,
                   VSZ_SESION, RSS_SESION)),
        # EL CGROUP ES LO QUE DELATA UN CONTENEDOR. Un dropper mira
        # /proc/1/cgroup o /proc/self/cgroup antes de instalarse: si ve
        # "/docker/..." se da media vuelta. En una maquina con systemd y sin
        # contenedores, una sesion de login cuelga de su scope de usuario y el
        # init de init.scope. Los dos llegaban VACIOS, que tampoco pasa nunca.
        ("/proc/%d/cgroup" % PID_LEYENDA,
         "0::/user.slice/user-0.slice/session-%d.scope\n" % SESION_LEYENDA),
        ("/proc/1/cgroup", "0::/init.scope\n"),
        ("/proc/1/status",
         make_status("systemd", 1, 0, 23316, 14528)),
    ]
    for ruta, texto in trabajos:
        if find(tree, ruta) is None:
            asegura_fichero(tree, ruta)
        patch_contents(tree, ruta, texto)


def asegura_fichero(tree, ruta):
    """Crea el nodo de un fichero de /proc que el pickle no traiga.

    createfs no siempre copia todas las entradas de /proc/PID, y un fichero
    que no existe es tan delator como uno vacio: "cat" contestaria "No such
    file or directory" para algo que hay en cualquier Linux.
    """
    padre = find(tree, ruta.rsplit("/", 1)[0])
    if padre is None:
        print(f"  AVISO: no existe {ruta.rsplit('/', 1)[0]}, se omite {ruta}")
        return
    nombre = ruta.rsplit("/", 1)[1]
    # 0444 y root:root, que es como se ven los ficheros de /proc.
    padre[A_CONTENTS].append(
        [nombre, T_FILE, 0, 0, 0, 0o100444, int(padre[A_CTIME]), b"", None,
         None])


def patch_mtab(tree):
    """Deja /etc/mtab y /proc/mounts legibles.

    Los dos venian como enlaces a /proc/<PID del constructor>/mounts, o sea
    rotos: "cat /etc/mtab" no devolvia nada. /proc/mounts pasa a ser un fichero
    con la tabla (su contenido lo pone PATCHES) y /etc/mtab apunta a el, que es
    exactamente lo que Debian tuvo durante anos y sigue siendo coherente.
    """
    for ruta, destino in (("/etc/mtab", "/proc/mounts"),):
        nodo = find(tree, ruta)
        if nodo is None:
            print(f"  AVISO: {ruta} no existe en el pickle, se omite")
            continue
        nodo[A_TYPE] = T_LINK
        nodo[A_TARGET] = destino
        nodo[A_SIZE] = len(destino)
        print(f"  OK: {ruta} -> {destino}")

    nodo = find(tree, "/proc/mounts")
    if nodo is not None and nodo[A_TYPE] == T_LINK:
        nodo[A_TYPE] = T_FILE
        nodo[A_TARGET] = None
        # Heredaba el 0777 del enlace. Los ficheros de /proc son 0444.
        nodo[A_MODE] = 0o100444
        print("  OK: /proc/mounts pasa de enlace roto a fichero con la tabla")


def patch_group_sudo(tree, user):
    """Anade un usuario al grupo sudo.

    La leyenda dice que alyosha usa sudo (su .bash_history esta lleno de
    "sudo apt install" y existe su .sudo_as_admin_successful), pero el
    grupo sudo estaba vacio: un "groups alyosha" lo delataba.
    """
    node = find(tree, "/etc/group")
    if node is None or not isinstance(node[A_CONTENTS], bytes):
        print("  AVISO: /etc/group sin contenido, se omite")
        return
    lines = node[A_CONTENTS].decode().splitlines()
    out = []
    for line in lines:
        if line.startswith("sudo:"):
            parts = line.split(":")
            members = [m for m in parts[3].split(",") if m]
            if user not in members:
                members.append(user)
            parts[3] = ",".join(members)
            line = ":".join(parts)
        out.append(line)
    data = ("\n".join(out) + "\n").encode()
    node[A_CONTENTS] = data
    node[A_SIZE] = len(data)
    print(f"  OK: /etc/group (anadido {user} al grupo sudo)")


def patch_shadow(tree, users_with_password):
    """Corrige /etc/shadow: contrasenas y fechas coherentes.

    El original tenia todas las cuentas bloqueadas con "!" (sin contrasena)
    y fechadas el dia del build. Pero la leyenda dice que estos usuarios
    entran por SSH con contrasena y que se crearon en marzo.
    """
    node = find(tree, "/etc/shadow")
    if node is None or not isinstance(node[A_CONTENTS], bytes):
        print("  AVISO: /etc/shadow sin contenido, se omite")
        return
    out = []
    for line in node[A_CONTENTS].decode().splitlines():
        parts = line.split(":")
        if len(parts) < 3:
            out.append(line)
            continue
        user = parts[0]
        if user in users_with_password:
            parts[1] = users_with_password[user]
            parts[2] = str(SHADOW_DAYS)
        out.append(":".join(parts))
    data = ("\n".join(out) + "\n").encode()
    node[A_CONTENTS] = data
    node[A_SIZE] = len(data)
    print(f"  OK: /etc/shadow (contrasenas y fechas de marzo)")


