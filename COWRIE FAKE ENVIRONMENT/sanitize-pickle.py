def copiar_etc_de_debian(honeyfs_dir, src_pickle):
    """Instala los /etc de serie que exporto el contenedor de construccion.

    build-dirtyland-fs.sh los deja en honeyfs-etc/, al lado del pickle. Se
    copian aqui y no en un paso aparte del README para que siga habiendo UN
    solo comando que puebla el honeyfs: un paso manual extra es un paso que
    algun dia se olvida, y el sintoma seria un banner de telnet vacio, que no
    se parece a un error.

    Si no estan, se avisa pero no se aborta: el pickle saneado es correcto
    igualmente, y quien todavia no haya regenerado con los paquetes de telnet
    tiene que poder seguir.
    """
    import os
    import shutil

    if not src_pickle:
        return
    origen = os.path.join(os.path.dirname(os.path.abspath(src_pickle)),
                          "honeyfs-etc")
    if not os.path.isdir(origen):
        print(f"  AVISO: no existe {origen}; el honeyfs se queda sin "
              f"/etc/issue.net y el banner de telnet saldra VACIO.")
        print("         Se genera regenerando el sistema de ficheros con "
              "build-dirtyland-fs.sh.")
        return

    destino = os.path.join(honeyfs_dir, "etc")
    os.makedirs(destino, exist_ok=True)
    # Se recorre el arbol y no solo el primer nivel: el sshd_config va en
    # ssh/sshd_config, y copiarlo plano lo dejaria en /etc/sshd_config, que
    # no es donde nadie lo busca.
    copiados = 0
    for raiz, _dirs, ficheros in os.walk(origen):
        rel = os.path.relpath(raiz, origen)
        sub = destino if rel == "." else os.path.join(destino, rel)
        os.makedirs(sub, exist_ok=True)
        for nombre in sorted(ficheros):
            ruta = os.path.join(raiz, nombre)
            if not os.path.isfile(ruta):
                continue
            shutil.copy2(ruta, os.path.join(sub, nombre))
            os.chmod(os.path.join(sub, nombre), 0o644)
            print(f"  OK: {sub}/{nombre}  (de Debian, no inventado)")
            copiados += 1
    if not copiados:
        print(f"  AVISO: {origen} esta vacio")


def linea_telnet_activa(texto):
    """True si un /etc/inetd.conf declara telnet SIN comentar.

    Debian deja su propia linea en el fichero, pero desactivada con el
    marcador "#<off># ". Comentada cuenta como ausente: es exactamente el
    estado en el que el fichero existe, parece correcto de un vistazo, y no
    declara nada.
    """
    for linea in texto.splitlines():
        if linea.lstrip().startswith("#"):
            continue
        campos = linea.split()
        if campos and campos[0] == "telnet":
            return True
    return False


