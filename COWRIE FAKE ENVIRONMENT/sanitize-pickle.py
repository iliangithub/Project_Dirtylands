def find(node, path):
    """Localiza un nodo del pickle por su ruta virtual."""
    cur = node
    for part in [x for x in path.split("/") if x]:
        cur = next((c for c in cur[A_CONTENTS] if c[A_NAME] == part), None)
        if cur is None:
            return None
    return cur


def patch_contents(tree, path, text):
    """Reescribe el contenido incrustado de un fichero del pickle."""
    node = find(tree, path)
    if node is None:
        print(f"  AVISO: {path} no existe en el pickle, se omite")
        return False
    data = text.encode()
    node[A_CONTENTS] = data
    # Los ficheros de /proc son virtuales: en un Linux real "ls -la" los
    # muestra con tamano 0. Los de /etc si tienen su tamano real.
    node[A_SIZE] = 0 if path.startswith("/proc/") else len(data)
    print(f"  OK: {path} ({len(data)} bytes)")
    return True


def patch_localtime(tree):
    """Apunta /etc/localtime a la zona de la leyenda.

    En Debian 13 este enlace ES la zona horaria: no hay /etc/timezone que
    valga. El contenedor de construccion lo deja en Etc/UTC, asi que sin este
    parche un "ls -l /etc/localtime" contradice a una maquina que se presenta
    como ucraniana ---y que ademas responde con fechas de Kyiv, porque el
    compose le pone TZ y le monta su propio /etc/localtime al contenedor.
    Dos mitades de la misma mentira que no se sostienen entre si.

    El destino tiene que EXISTIR en el pickle o el enlace queda roto, que es
    peor que apuntar a UTC: se avisa en ese caso en vez de darlo por hecho.
    """
    node = find(tree, "/etc/localtime")
    if node is None:
        print("  AVISO: /etc/localtime no existe en el pickle, se omite")
        return
    if find(tree, LOCALTIME_DESTINO) is None:
        print(f"  AVISO: {LOCALTIME_DESTINO} no esta en el pickle; el enlace")
        print( "         quedaria roto. Se deja como estaba. Comprueba que")
        print( "         tzdata entro en el contenedor de construccion.")
        return
    node[A_TYPE] = T_LINK
    node[A_TARGET] = LOCALTIME_DESTINO
    node[A_SIZE] = len(LOCALTIME_DESTINO)
    print(f"  OK: /etc/localtime -> {LOCALTIME_DESTINO}")


def patch_destinos_de_enlaces(tree):
    """Deja los destinos de los enlaces como los escribe un Linux de verdad.

    createfs.py guarda el destino recortando el localroot
    ---os.path.realpath(path)[len(localroot):]--- y con localroot="/" eso quita
    la barra inicial. El resultado se ve en cualquier "ls -l":

        localtime -> usr/share/zoneinfo/Europe/Kyiv
        S01cron   -> etc/init.d/cron

    Ninguna de esas rutas existe tal y como se muestra. Un Linux real imprime
    "/usr/share/zoneinfo/Europe/Kyiv".

    Ademas descuadra el tamano. st_size de un enlace es la longitud de lo que
    devuelve readlink, o sea el destino ORIGINAL ("../init.d/cron", 14), pero
    lo que se guarda es el destino RESUELTO ("etc/init.d/cron", 15). En un
    Linux real ese numero y la ruta que sale detras de la flecha siempre miden
    lo mismo. Se recalcula.

    Lo que NO se puede recuperar aqui es la forma relativa original: cuando
    createfs.py llama a realpath, "../init.d/cron" ya se ha perdido. Queda un
    enlace absoluto, que es valido y coherente, aunque un Debian de serie
    tenga ahi uno relativo.

    De paso arregla algo que hoy funciona por casualidad: getfile() de Cowrie
    solo trata el destino como absoluto si empieza por "/", y si no, lo resuelve
    contra un cwd que nunca se actualiza (la linea esta comentada en fs.py) y
    que por eso vale "". Con la barra puesta, los enlaces entran por la rama
    que les corresponde en vez de depender de ese descuido.
    """
    arreglados = 0
    def recorrer(nodo):
        nonlocal arreglados
        hijos = nodo[A_CONTENTS]
        if not isinstance(hijos, list):
            return
        for hijo in hijos:
            if hijo[A_TYPE] == T_LINK:
                destino = hijo[A_TARGET]
                if isinstance(destino, str) and destino:
                    if not destino.startswith("/"):
                        destino = "/" + destino
                        hijo[A_TARGET] = destino
                        arreglados += 1
                    hijo[A_SIZE] = len(destino)
            else:
                recorrer(hijo)

    recorrer(tree)
    print(f"  OK: {arreglados} destinos de enlace con su barra inicial")
    return arreglados


def patch_pid_del_constructor(tree):
    """Quita del pickle el PID del contenedor que lo genero.

    createfs.py recorre /proc del contenedor de construccion, asi que el pickle
    se queda con el directorio de SU PROPIO proceso: /proc/9355 (o el numero
    que tocara ese dia) y un /proc/self apuntando ahi. Se ve a simple vista:

        # ls /proc
        1  9355  acpi  asound  ...

    Dos numeros y punto, y el segundo no aparece en "ps aux". Cualquiera que
    mire /proc ve que ese proceso no existe.

    Se renombra al PID que la leyenda ya usa para la sesion en
    ps_command_output.json, para que el numero que sale en /proc sea uno de los
    que "ps" reconoce. No se clonan los 85 procesos del JSON: cada uno traeria
    su medio centenar de ficheros y engordaria el pickle sin que nadie los mire.
    """
    proc = find(tree, "/proc")
    if proc is None:
        print("  AVISO: el pickle no tiene /proc, se omite")
        return

    numericos = [c for c in proc[A_CONTENTS] if c[A_NAME].isdigit()]
    constructor = [c for c in numericos if c[A_NAME] != "1"]
    if not constructor:
        print("  OK: /proc no tiene el PID del constructor")
        return

    viejo = constructor[0][A_NAME]
    for nodo in constructor[1:]:
        proc[A_CONTENTS].remove(nodo)
    constructor[0][A_NAME] = str(PID_LEYENDA)
    print(f"  OK: /proc/{viejo} renombrado a /proc/{PID_LEYENDA} (el bash de ps)")

    enlace = find(tree, "/proc/self")
    if enlace is not None and enlace[A_TYPE] == T_LINK:
        enlace[A_TARGET] = f"/proc/{PID_LEYENDA}"
        enlace[A_SIZE] = len(enlace[A_TARGET])
        print(f"  OK: /proc/self -> /proc/{PID_LEYENDA}")


