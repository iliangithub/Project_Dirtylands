"""
test_sanitize_pickle.py — el saneador del pickle y lo que deja en el honeyfs.

    python3 "COWRIE FAKE ENVIRONMENT/tests/test_sanitize_pickle.py"

Se monta un arbol sintetico con la misma forma que produce createfs.py y se
llaman las funciones del saneador de verdad. No toca nada del sistema: escribe
solo en un directorio temporal propio.

Lo que se comprueba:

  - que los ficheros de la LEYENDA se reescriben (hostname, resolv.conf...) y
    que el rastro del contenedor de construccion desaparece;
  - que los /etc de serie exportados por ese contenedor se COPIAN al honeyfs
    en vez de inventarse, y que entre ellos esta etc/issue.net, que es de
    donde Cowrie saca el banner de telnet;
  - que sin esa exportacion NO se inventa un issue.net, solo se avisa;
  - y que el aviso de coherencia salta cuando el pickle se genero SIN los
    paquetes de telnet. Ese es el que evita la degradacion silenciosa: un
    senuelo que ofrece el 23 y no tiene en su disco con que explicarlo.

El aviso se comprueba en sus DOS mitades, porque viven en sitios distintos:
el listado en el pickle, y el contenido de /etc/inetd.conf en el honeyfs
---ese fichero no figura en la EMBED_PATHS de createfs.py---. Mirar solo la
primera daba un OK enganoso contra un Debian de verdad: inetutils-telnetd en
trixie instala el binario y nada mas, asi que el fichero llegaba entero
comentado. Este arbol sintetico lo daba por bueno porque se lo inventaba ya
activo; ahora se prueban los dos estados por separado.

Se serializa con pickle.dumps/loads y no pasandole el descriptor de fichero.
Da igual en Debian, pero asi la prueba no depende de como se comporte el
sistema de ficheros de la maquina donde se ejecute.
"""

