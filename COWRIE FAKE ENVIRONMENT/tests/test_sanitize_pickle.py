def comprueba(que, esperado, obtenido):
    global OK, MAL
    if esperado == obtenido:
        OK += 1
        print("  ok    %s" % que)
    else:
        MAL += 1
        print("  FALLO %s\n          esperaba %r\n          obtuvo   %r"
              % (que, esperado, obtenido))


# --- Un arbol con la forma que genera createfs.py --------------------------
T_LINK, T_DIR, T_FILE = 0, 1, 2


def carpeta(nombre, hijos):
    return [nombre, T_DIR, 0, 0, 4096, 0o755, 0, hijos, None, None]


def fichero(nombre, datos=b""):
    return [nombre, T_FILE, 0, 0, len(datos), 0o644, 0, datos, None, None]


def enlace(nombre, destino):
    """createfs.py guarda el destino sin la barra inicial, y el tamano CON."""
    return [nombre, T_LINK, 0, 0, len("/" + destino), 0o777, 0, [], destino,
            None]


def arbol(con_telnet: bool):
    etc = [fichero("hostname", b"caja-de-build\n"),
           fichero("hosts", b"127.0.0.1 caja-de-build\n"),
           fichero("resolv.conf", b"# Generated by Docker Engine\n"),
           # Debian 13 no trae /etc/timezone: la zona la fija este enlace, y
           # el contenedor de construccion lo deja en UTC.
           enlace("localtime", "usr/share/zoneinfo/Etc/UTC"),
           fichero("group", b"root:x:0:\nsudo:x:27:\n"),
           fichero("shadow", b"alyosha:!:20000:0:99999:7:::\n"),
           # createfs.py los deja apuntando al PID de SU proceso, o sea rotos.
           enlace("mtab", "proc/9355/mounts"),
           fichero("fstab", b"# UNCONFIGURED FSTAB\n")]
    sbin = []
    if con_telnet:
        # Sin contenido a proposito: /etc/inetd.conf NO esta en la EMBED_PATHS
        # de createfs.py, asi que en el pickle real llega con A_CONTENTS vacio
        # y lo que responde un "cat" sale del honeyfs.
        etc.append(fichero("inetd.conf"))
        sbin = [fichero("inetd"), fichero("in.telnetd")]
    return carpeta("/", [
        carpeta("etc", etc),
        carpeta("usr", [carpeta("lib", [fichero("os-release", b"viejo\n")]),
                        carpeta("sbin", sbin),
                        carpeta("share", [carpeta("zoneinfo", [
                            carpeta("Etc", [fichero("UTC")]),
                            carpeta("Europe", [fichero("Kyiv")])])])]),
        carpeta("proc", [fichero("version"), fichero("cpuinfo"),
                         fichero("meminfo"), fichero("modules"),
                         fichero("partitions"), fichero("swaps"),
                         enlace("mounts", "proc/9355/mounts"),
                         # El rastro del contenedor que genero el pickle.
                         enlace("self", "proc/9355"),
                         # "status" viene del contenedor de construccion,
                         # o sea VACIO; "cgroup" ni siquiera viene, que
                         # createfs no copia todas las entradas de /proc/PID.
                         carpeta("9355", [fichero("mounts"),
                                          fichero("status")]),
                         carpeta("1", [fichero("mounts")])]),
    ])


def clon(con_telnet: bool):
    """Copia independiente, para que una prueba no ensucie a la siguiente."""
    return pickle.loads(pickle.dumps(arbol(con_telnet)))


def leer(tree, ruta):
    n = san.find(tree, ruta)
    if n is None or not isinstance(n[san.A_CONTENTS], bytes):
        return None
    return n[san.A_CONTENTS].decode()


