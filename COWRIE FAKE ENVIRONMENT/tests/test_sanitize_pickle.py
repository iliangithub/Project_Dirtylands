    comprueba("la misma linea sin comentar si cuenta",
              True, san.linea_telnet_activa(
                  "telnet\tstream\ttcp\tnowait\troot"
                  "\t/usr/sbin/tcpd\t/usr/sbin/telnetd\n"))
    comprueba("un servicio que solo empieza por 'telnet' no cuela",
              False, san.linea_telnet_activa(
                  "telnets\tstream\ttcp\tnowait\troot\tinternal\n"))

    fs_conf = tmp / "fs_conf"
    (fs_conf / "honeyfs-etc").mkdir(parents=True)
    (fs_conf / "fs.pickle.new").write_bytes(b"x")
